# 9. CRC32 Standard Table (IEEE 802.3, poly 0xEDB88320)
def _generate_crc32_table() -> bytes:
    table = []
    for i in range(256):
        c = i
        for _ in range(8):
            if c & 1:
                c = 0xEDB88320 ^ (c >> 1)
            else:
                c = c >> 1
        table.append(c)
    return struct.pack("<256I", *table)

CRC32_TABLE_LE = _generate_crc32_table()

