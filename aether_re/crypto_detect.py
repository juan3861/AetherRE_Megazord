class CryptoScanner:
    """Forensic scanner for cryptographic constants and algorithms in binary buffers."""

    def __init__(self, data: bytes, base_addr: int = 0x00400000):
        self.data = data
        self.base_addr = base_addr
        self.sections: List[Tuple[int, int, int, str]] = []  # (raw_start, raw_end, va_start, name)
        self._parse_pe_sections()

    def _parse_pe_sections(self) -> None:
        """Parses PE sections to correlate file offsets to Virtual Addresses and section names."""
        if not HAS_PEFILE or len(self.data) < 512 or self.data[:2] != b"MZ":
            return
        try:
            pe = pefile.PE(data=self.data, fast_load=True)
            image_base = getattr(pe.OPTIONAL_HEADER, "ImageBase", self.base_addr)
            for s in pe.sections:
                raw_start = s.PointerToRawData
                raw_size = s.SizeOfRawData
                raw_end = raw_start + raw_size
                va_start = image_base + s.VirtualAddress
                name = s.Name.decode("latin-1", errors="ignore").strip("\x00")
                self.sections.append((raw_start, raw_end, va_start, name))
        except Exception:
            pass

    def _offset_to_va_and_section(self, offset: int) -> Tuple[Optional[int], Optional[str]]:
        for raw_start, raw_end, va_start, name in self.sections:
            if raw_start <= offset < raw_end:
                va = va_start + (offset - raw_start)
                return va, name
        return None, None

    def scan(self, max_matches_per_sig: int = 10) -> List[CryptoMatch]:
        """Scans the binary buffer against all registered cryptographic signatures."""
        matches: List[CryptoMatch] = []

        for algo, prim_type, sig_bytes, confidence, desc in SIGNATURES:
            sig_len = len(sig_bytes)
            start_pos = 0
            count = 0

            while start_pos < len(self.data) and count < max_matches_per_sig:
                idx = self.data.find(sig_bytes, start_pos)
                if idx == -1:
                    break

                va, sec_name = self._offset_to_va_and_section(idx)
                matches.append(
                    CryptoMatch(
                        algorithm=algo,
                        primitive_type=prim_type,
                        file_offset=idx,
                        virtual_address=va,
                        section_name=sec_name,
                        size_bytes=sig_len,
                        confidence=confidence,
                        description=desc,
                    )
                )
                start_pos = idx + 1
                count += 1

        return matches


def scan_file_for_crypto(file_path: str | Path) -> Dict[str, Any]:
    """Analyzes a binary file on disk and returns full cryptographic inventory."""
    p = Path(file_path).resolve()
    if not p.exists() or not p.is_file():
        raise FileNotFoundError(f"Binary file not found: {p}")

    start_time = time.time()
    data = p.read_bytes()
    scanner = CryptoScanner(data)
    matches = scanner.scan()
    elapsed = time.time() - start_time

    # Group matches by algorithm
    unique_algos = sorted(list({m.algorithm for m in matches}))
    high_conf_matches = [m for m in matches if m.confidence == "HIGH"]

    return {
        "target": str(p),
        "file_size_bytes": len(data),
        "elapsed_seconds": round(elapsed, 4),
        "total_constants_detected": len(matches),
        "high_confidence_matches_count": len(high_conf_matches),
        "identified_algorithms": unique_algos,
        "matches": [asdict(m) for m in matches],
    }
